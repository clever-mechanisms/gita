    @Test func missingPromisedObjectsNeverTriggerAnImplicitFetch() async throws {
        let fixture = try await ReferenceFixture()
        defer { fixture.remove() }
        let capability = try await fixture.git(["--no-lazy-fetch", "--version"], allowFailure: true)
        try #require(capability.exitCode == 0 || capability.exitCode == 129)
        let supportsNoLazyFetch = capability.exitCode == 0
        let commit = try await fixture.oid("HEAD")
        let remote = fixture.container.appendingPathComponent("remote.git")
        try await fixture.git(["clone", "--bare", "--no-hardlinks", fixture.root.path, remote.path])
        try await fixture.git(["config", "remote.origin.url", remote.path])
        try await fixture.git(["config", "remote.origin.promisor", "true"])
        try await fixture.git(["config", "remote.origin.partialclonefilter", "blob:none"])
        let object = fixture.root.appendingPathComponent(".git/objects/" + commit.prefix(2) + "/" + commit.dropFirst(2))
        try FileManager.default.removeItem(at: object)
        let objectDirectory = fixture.root.appendingPathComponent(".git/objects").path
        let objectsBefore = try FileManager.default.subpathsOfDirectory(atPath: objectDirectory).sorted()
        let expected: any Error =
            supportsNoLazyFetch ? GitError.invalidReference : RepositoryInspectionError.partialCloneUnsupported
        await #expect(throws: GitError.self) { _ = try await fixture.details("main") }
        await expectError(expected) {
            try await fixture.service.createTag(name: "missing", commitID: commit, annotation: nil)
        }
        #expect(!FileManager.default.fileExists(atPath: object.path))
        #expect(try FileManager.default.subpathsOfDirectory(atPath: objectDirectory).sorted() == objectsBefore)
        if supportsNoLazyFetch {
            #expect(
                try await fixture.git(["--no-lazy-fetch", "cat-file", "-e", commit], allowFailure: true).exitCode != 0)
        }
        #expect(try await !fixture.exists("refs/tags/missing"))
    }

