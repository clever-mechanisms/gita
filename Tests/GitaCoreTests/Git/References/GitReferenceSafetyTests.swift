        let service = GitService(root: fixture.root, runner: runner)
        await #expect(throws: GitError.self) { try await service.deleteTag(current) }
        #expect(try await fixture.oid("refs/tags/release") == replacement)
        let arguments = await runner.deletionArguments
        #expect(arguments?.contains("--no-deref") == true)
        #expect(arguments?.last == current.objectID)
    }

    @Test func reviewBindsSourceHeadConfigurationWorktreeAndRepositoryButNotUnrelatedRefs() async throws {
