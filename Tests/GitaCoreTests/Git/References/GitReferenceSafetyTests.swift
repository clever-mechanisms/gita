        let blobDetails = try await fixture.details("blob", kind: .tag)
        let outer = try await fixture.details("outer", kind: .tag)
        #expect(blobDetails.objectID == blob && blobDetails.objectType == "blob" && blobDetails.commitID == nil)
        #expect(outer.objectID == (try await fixture.oid("refs/tags/outer")))
        #expect(outer.commitID == (try await fixture.oid("HEAD")))
        try await fixture.service.deleteTag(blobDetails)
        try await fixture.service.deleteTag(outer)
        #expect(try await !fixture.exists("refs/tags/blob"))
        #expect(try await fixture.exists("refs/tags/inner"))
    }

    @Test func changedAnnotationAtSameCommitInvalidatesReviewAndDeleteUsesRawCAS() async throws {
        let fixture = try await ReferenceFixture()
        defer { fixture.remove() }
        let commit = try await fixture.oid("HEAD")
        try await fixture.service.createTag(name: "release", commitID: commit, annotation: "Original")
        let old = try await fixture.details("release", kind: .tag)
        try await fixture.git(["tag", "-a", "-f", "release", "-m", "Replacement"])
        let current = try await fixture.details("release", kind: .tag)
        #expect(old.commitID == current.commitID && old.objectID != current.objectID)
        await expectReferenceError(.staleReference) { try await fixture.service.deleteTag(old) }
        try await fixture.git(["tag", "-a", "another", "-m", "Racing replacement"])
        let replacement = try await fixture.oid("refs/tags/another")
