    @Test func tagsAreUnsignedAtExplicitCommitAndNeverLaunchConfiguredPrograms() async throws {
        let fixture = try await ReferenceFixture()
        defer { fixture.remove() }
        let first = try await fixture.oid("HEAD")
        try fixture.write("file.txt", "later\n")
        try await fixture.commit("Later")
        let sentinel = fixture.container.appendingPathComponent("unexpected-program")
        let marker = fixture.container.appendingPathComponent("program-ran")
        // A fixture path generated by UUID has no shell metacharacters.
        try Data(("#!/bin/sh\ntouch '" + marker.path + "'\nexit 1\n").utf8).write(to: sentinel)
        #expect(chmod(sentinel.path, 0o700) == 0)
        for key in ["gpg.program", "core.editor"] { try await fixture.git(["config", key, sentinel.path]) }
        try await fixture.git(["config", "tag.gpgSign", "true"])
        try await fixture.git(["config", "tag.forceSignAnnotated", "true"])
        try await fixture.service.createTag(name: "light", commitID: first, annotation: nil)
        try await fixture.service.createTag(
            name: "annotated", commitID: first, annotation: "Release one\n\nExact notes\n")
        let light = try await fixture.details("light", kind: .tag)
        let annotated = try await fixture.details("annotated", kind: .tag)
        #expect(light.objectType == "commit" && light.objectID == first && light.commitID == first)
        #expect(annotated.objectType == "tag" && annotated.objectID != first && annotated.commitID == first)
        let object = try await fixture.git(["cat-file", "tag", annotated.objectID]).text
        #expect(object.hasSuffix("Release one\n\nExact notes\n"))
        #expect(!object.contains("BEGIN PGP SIGNATURE"))
        #expect(!FileManager.default.fileExists(atPath: marker.path))
        await #expect(throws: GitError.self) {
            try await fixture.service.createTag(name: "light", commitID: first, annotation: nil)
        }
        for value in ["HEAD", String(first.prefix(12)), annotated.objectID] {
            await expectReferenceError(.invalidReference) {
                try await fixture.service.createTag(name: "invalid", commitID: value, annotation: nil)
            }
        }
        for annotation in [" \n", "NUL\0message", String(repeating: "x", count: 65_537)] {
            await #expect(throws: ReferenceError.tagMessage) {
                try await fixture.service.createTag(name: "empty", commitID: first, annotation: annotation)
            }
        }
        #expect(try await fixture.oid("refs/tags/light") == first)
    }

    @Test func nonCommitAndNestedTagsRetainRawIdentityAndCanBeDeleted() async throws {
        let fixture = try await ReferenceFixture()
