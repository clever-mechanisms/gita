    @Test func allReferenceWritesRefuseAnActiveMerge() async throws {
        let fixture = try await ReferenceFixture()
        defer { fixture.remove() }
        try await fixture.git(["branch", "topic"])
        let commit = try await fixture.oid("HEAD")
        try await fixture.service.createTag(name: "existing", commitID: commit, annotation: nil)
        let main = try await fixture.details("main")
        let topic = try await fixture.details("topic")
        let tag = try await fixture.details("existing", kind: .tag)
        try await fixture.git(["switch", "-c", "incoming"])
        try fixture.write("incoming.txt", "incoming\n")
        try await fixture.commit("Incoming")
        try await fixture.git(["switch", "main"])
        try await fixture.git(["merge", "--no-commit", "--no-ff", "incoming"])
        await expectReferenceError(.operationActive) { try await fixture.service.renameBranch(topic, to: "renamed") }
        await expectReferenceError(.operationActive) { try await fixture.service.deleteMergedBranch(topic) }
        await expectReferenceError(.operationActive) { try await fixture.service.setUpstream(topic, to: main) }
        await expectReferenceError(.operationActive) {
            try await fixture.service.createTag(name: "new", commitID: commit, annotation: nil)
        }
        await expectReferenceError(.operationActive) { try await fixture.service.deleteTag(tag) }
        #expect(try await fixture.exists("refs/heads/topic"))
        #expect(try await fixture.exists("refs/tags/existing"))
    }

