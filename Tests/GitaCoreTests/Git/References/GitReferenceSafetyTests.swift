    @Test func olderGitRechecksPartialCloneConfigurationBeforeObjectReads() async throws {
        let fixture = try await ReferenceFixture()
        defer { fixture.remove() }
        let runner = LegacyReferenceRunner()
        let service = GitService(root: fixture.root, runner: runner)
        let main = try await service.referenceDetails(fullName: "refs/heads/main")
        let reads = await runner.objectCommands
        try await fixture.git(["config", "remote.origin.promisor", "yes"])
        await #expect(throws: RepositoryInspectionError.partialCloneUnsupported) {
            _ = try await service.referenceDetails(fullName: "refs/heads/main")
        }
        await #expect(throws: RepositoryInspectionError.partialCloneUnsupported) {
            try await service.createTag(name: "blocked", commitID: main.objectID, annotation: nil)
        }
        #expect(await runner.objectCommands == reads)
        try await fixture.git(["config", "remote.origin.promisor", "false"])
        try await fixture.git(["config", "extensions.partialClone", "origin"])
        await #expect(throws: RepositoryInspectionError.partialCloneUnsupported) {
            _ = try await service.referenceDetails(fullName: "refs/heads/main")
        }
        #expect(await runner.objectCommands == reads)
        try await fixture.git(["config", "--unset", "extensions.partialClone"])
        #expect(try await service.referenceDetails(fullName: "refs/heads/main").objectID == main.objectID)
        #expect(try await !fixture.exists("refs/tags/blocked"))
        #expect(await runner.probes == 1)
        #expect(await runner.unsupportedFlags == 0)
    }

