    @Test func preflightWaitsForMutationGateAndCancelledWaiterNeverWrites() async throws {
        let fixture = try await ReferenceFixture()
        defer { fixture.remove() }
        try await fixture.git(["branch", "other"])
        try await fixture.git(["branch", "topic"])
        let runner = ReferenceGateRunner()
        let controlled = GitService(root: fixture.root, runner: runner)
        let expected = try await controlled.referenceDetails(fullName: "refs/heads/topic")
        let checkout = Task { try await controlled.checkout(ref: "other") }
        await runner.waitForPause()
        let cancelled = Task { try await controlled.renameBranch(expected, to: "cancelled") }
        let stale = Task { try await controlled.renameBranch(expected, to: "stale") }
        cancelled.cancel()
        await runner.resume()
        try await checkout.value
        do {
            try await cancelled.value
            Issue.record("Expected cancellation")
        } catch { #expect(error is CancellationError) }
        await expectReferenceError(.staleReference) { try await stale.value }
        #expect(await runner.renameCalls == 0)
        #expect(try await fixture.exists("refs/heads/topic"))
    }

