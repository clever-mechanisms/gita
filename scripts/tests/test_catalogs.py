"""Catalog validation, merge and compilation in scripts/catalogs.py, on temporary fixtures only."""
import contextlib
import io
import json
import plistlib
import sys
import tempfile
import unittest
from pathlib import Path
from unittest import mock

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import catalogs  # noqa: E402
from strings_check import CatalogError, LOCALES  # noqa: E402

COMMITS = "%lld commits"
HELLO = "Hello %@"
LOCALIZABLE_FILE = "Localizable.xcstrings"
INFO_PLIST_FILE = "InfoPlist.xcstrings"
SWIFT_FILE = "View.swift"
SOURCES = "Sources"


def unit(value, state="translated"):
    return {"stringUnit": {"state": state, "value": value}}


def catalog(strings):
    return {"sourceLanguage": "en", "strings": strings, "version": "1.0"}


def all_locales(value):
    return {"localizations": {locale: unit(value) for locale in LOCALES}}


class Fixture:
    """A temporary project root with Resources/ and owned Swift sources."""

    def __init__(self, directory):
        self.root = Path(directory)
        self.resources = self.root / "Resources"
        self.resources.mkdir()
        (self.resources / "Plurals").mkdir()
        for target in catalogs.OWNED_TARGETS:
            (self.root / SOURCES / target).mkdir(parents=True)
            (self.root / SOURCES / target / SWIFT_FILE).write_text("")

    def write(self, name, value):
        (self.resources / name).write_text(json.dumps(value))

    def patch(self):
        return mock.patch.multiple(catalogs, ROOT=self.root, RESOURCES=self.resources)


class ValidateTests(unittest.TestCase):
    def test_renders_complete_and_missing_locales(self):
        strings = {HELLO: {"localizations": {"en": unit(HELLO), "de": unit("Hallo %@"), "fr": unit("Salut %@", "new")}},
                   "Fixed": {"shouldTranslate": False}}
        rendered, missing = catalogs.validate_catalog(catalog(strings), catalogs.LOCALIZABLE)
        self.assertEqual(rendered["de"]["strings"], {HELLO: "Hallo %@", "Fixed": "Fixed"})
        self.assertEqual(rendered["fr"]["strings"][HELLO], HELLO)
        self.assertEqual(missing["fr"], [HELLO])
        self.assertEqual(missing["en"], [])

    def test_external_plurals_fill_locales(self):
        def spec(one, other):
            return {COMMITS: {"format": "%#@count@", "variables": {"count": {"type": "lld", "forms": {
                "one": one, "other": other}}}}}

        plurals = {"en": spec("%lld commit", COMMITS), "de": spec("%lld Commit", "%lld Commits")}
        rendered, missing = catalogs.validate_catalog(catalog({COMMITS: {}}), catalogs.LOCALIZABLE, plurals)
        self.assertNotIn(COMMITS, missing["de"])
        self.assertEqual(rendered["de"]["plurals"][COMMITS]["count"]["other"], "%1$lld Commits")
        self.assertIn(COMMITS, missing["fr"])

    def test_rejections(self):
        cases = [({"version": "2.0", "sourceLanguage": "en", "strings": {}}, "version 1.0"),
                 (catalog({}), "empty"),
                 (catalog({"k": {"extractionState": "stale"}}), "stale entry"),
                 (catalog({"k": {"extractionState": "odd"}}), "unsupported extractionState"),
                 (catalog({"k": {"shouldTranslate": "no"}}), "shouldTranslate must be Boolean"),
                 (catalog({"k": {"isCommentAutoGenerated": 1}}), "isCommentAutoGenerated must be Boolean"),
                 (catalog({"k": {"localizations": {"xx": {}}}}), "unexpected localization"),
                 (catalog({"%1$@ %3$@": {}}), "positional gaps"),
                 (catalog({"k": {"localizations": {"en": {"stringUnit": unit("k")["stringUnit"], "x": 1}}}}),
                  "explicit English stringUnit")]
        for value, message in cases:
            with self.subTest(message=message), self.assertRaisesRegex(CatalogError, message):
                catalogs.validate_catalog(value, catalogs.LOCALIZABLE)
        with self.assertRaisesRegex(CatalogError, "unknown catalog keys"):
            catalogs.validate_catalog(catalog({"k": {}}), catalogs.LOCALIZABLE, {"de": {"other": {}}})

    def test_thai_plural_forms_need_only_other(self):
        def spec(**forms):
            return {COMMITS: {"format": "%#@count@", "variables": {"count": {"type": "lld", "forms": forms}}}}

        plurals = {"en": spec(one="%lld commit", other=COMMITS), "th": spec(other="%lld commit")}
        rendered, missing = catalogs.validate_catalog(catalog({COMMITS: {}}), catalogs.LOCALIZABLE, plurals)
        self.assertEqual(missing["th"], [])
        self.assertEqual(rendered["th"]["plurals"][COMMITS]["count"]["other"], "%1$lld commit")


class MergeTests(unittest.TestCase):
    def stringsdata(self, directory, fixture, entries):
        source = fixture.root / SOURCES / "GitaCore" / SWIFT_FILE
        data = {"source": str(source), "tables": {"Localizable": entries}, "version": 1}
        (Path(directory) / "a.stringsdata").write_text(json.dumps(data))
        other = dict(data, source=str(fixture.root / SOURCES / "GitaUI" / SWIFT_FILE), tables={})
        (Path(directory) / "b.stringsdata").write_text(json.dumps(other))

    def test_merge_adds_keeps_and_drops(self):
        with tempfile.TemporaryDirectory() as root, tempfile.TemporaryDirectory() as data:
            fixture = Fixture(root)
            fixture.write(LOCALIZABLE_FILE, catalog({"Old": {}, "Kept": {"extractionState": "manual"},
                                                     "Stay": {"extractionState": "stale"}}))
            self.stringsdata(data, fixture, [{"key": "New", "comment": "A button"}, {"key": "Stay"}, {"key": ""}])
            with fixture.patch(), contextlib.redirect_stdout(io.StringIO()) as output:
                catalogs.merge(Path(data), allow_drop=True)
            merged = json.loads((fixture.resources / LOCALIZABLE_FILE).read_text())["strings"]
        self.assertEqual(list(merged), ["Kept", "New", "Stay"])
        self.assertEqual(merged["New"]["comment"], "A button")
        self.assertNotIn("extractionState", merged["Stay"])
        self.assertIn("3 keys, 1 added, 1 removed", output.getvalue())

    def test_merge_refuses_large_drop_and_conflicts(self):
        with tempfile.TemporaryDirectory() as root, tempfile.TemporaryDirectory() as data:
            fixture = Fixture(root)
            fixture.write(LOCALIZABLE_FILE, catalog({"Old": {}}))
            self.stringsdata(data, fixture, [{"key": "New"}])
            with fixture.patch(), self.assertRaisesRegex(CatalogError, "would be dropped"):
                catalogs.merge(Path(data), allow_drop=False)
            self.stringsdata(data, fixture, [{"key": "K", "value": "a"}, {"key": "K", "value": "b"}])
            with fixture.patch(), self.assertRaisesRegex(CatalogError, "conflicting English defaults"):
                catalogs.merge(Path(data), allow_drop=True)


class CompileTests(unittest.TestCase):
    def test_compile_writes_locales_and_removes_stale_files(self):
        with tempfile.TemporaryDirectory() as root, tempfile.TemporaryDirectory() as output:
            fixture = Fixture(root)
            fixture.write(LOCALIZABLE_FILE, catalog({HELLO: all_locales(HELLO)}))
            fixture.write(INFO_PLIST_FILE, catalog({"Name": all_locales("Gita")}))
            stale = Path(output) / "xx.lproj"
            stale.mkdir()
            (stale / "Localizable.strings").write_bytes(b"")
            old_plural = Path(output) / "de.lproj" / "Localizable.stringsdict"
            old_plural.parent.mkdir()
            old_plural.write_bytes(b"")
            with fixture.patch(), contextlib.redirect_stdout(io.StringIO()):
                catalogs.compile_catalogs(Path(output))
            strings = plistlib.loads((Path(output) / "de.lproj" / "Localizable.strings").read_bytes())
            self.assertEqual(strings, {HELLO: HELLO})
            self.assertFalse(stale.exists())
            self.assertFalse(old_plural.exists())

    def test_compile_refuses_foreign_resources(self):
        with tempfile.TemporaryDirectory() as root, tempfile.TemporaryDirectory() as output:
            fixture = Fixture(root)
            fixture.write(LOCALIZABLE_FILE, catalog({HELLO: all_locales(HELLO)}))
            fixture.write(INFO_PLIST_FILE, catalog({}))
            foreign = Path(output) / "xx.lproj"
            foreign.mkdir()
            (foreign / "Other.png").write_bytes(b"")
            with fixture.patch(), self.assertRaisesRegex(CatalogError, "other resources"):
                catalogs.compile_catalogs(Path(output))
            with fixture.patch(), self.assertRaisesRegex(CatalogError, "not source Resources"):
                catalogs.compile_catalogs(fixture.resources)


if __name__ == "__main__":
    unittest.main()
