#!/usr/bin/env python3
"""Gita string catalog merge, checking and bundle compilation; works with the Command Line Tools alone.

Translations stay in catalogs and per-locale Resources/Plurals/<locale>.json files;
no translation module is imported or executed. See strings_check.external_plural
for the typed plural schema. Unsupported variation shapes fail without flattening.
"""
import argparse
import copy
import json
import os
from pathlib import Path
import plistlib
import sys
import tempfile

from strings_check import (CatalogError, LOCALES, STRING_UNIT, TRANSLATED, catalog_localization,
                           external_plural, fields, parse_format, string_unit, text)

ROOT = Path(__file__).resolve().parent.parent
RESOURCES = ROOT / "Resources"
LOCALIZABLE = "Localizable"
INFO_PLIST = "InfoPlist"
TABLES = (LOCALIZABLE, INFO_PLIST)
OUTPUTS = {"Localizable.strings", "Localizable.stringsdict", "InfoPlist.strings", "InfoPlist.stringsdict"}

# Catalog and rendered-table keys.
VERSION, SOURCE_LANGUAGE, STRINGS = "version", "sourceLanguage", "strings"
CATALOG_FIELDS = {VERSION, SOURCE_LANGUAGE, STRINGS}
COMMENT, EXTRACTION_STATE, LOCALIZATIONS = "comment", "extractionState", "localizations"
SHOULD_TRANSLATE, COMMENT_AUTO_GENERATED = "shouldTranslate", "isCommentAutoGenerated"
ENTRY_FIELDS = {COMMENT, EXTRACTION_STATE, COMMENT_AUTO_GENERATED, SHOULD_TRANSLATE, LOCALIZATIONS}
PLURALS = "plurals"
MANUAL, STALE = "manual", "stale"
# Extracted .stringsdata keys and merged entries.
SOURCE, TABLES_KEY, VALUE, COMMENTS = "source", "tables", "value", "comments"
STRINGSDATA_FIELDS = {SOURCE, TABLES_KEY, VERSION}
OWNED_TARGETS = ("GitaCore", "GitaUI")
MAX_JSON_BYTES = 32 * 1024 * 1024


def unique_object(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise CatalogError(f"duplicate JSON key {key!r}")
        result[key] = value
    return result


def read_json(path):
    if not path.is_file() or path.is_symlink():
        raise CatalogError(f"{path}: expected a regular JSON file")
    if path.stat().st_size > MAX_JSON_BYTES:
        raise CatalogError(f"{path}: JSON exceeds 32 MB")
    try:
        return json.loads(path.read_text(encoding="utf-8"), object_pairs_hook=unique_object)
    except ValueError as error:  # includes UnicodeError and CatalogError
        raise CatalogError(f"{path}: {error}") from error


def atomic_write(path, data):
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.is_symlink():
        raise CatalogError(f"{path}: refusing to replace a symbolic link")
    descriptor, temporary = tempfile.mkstemp(prefix="." + path.name + ".", dir=path.parent)
    try:
        with os.fdopen(descriptor, "wb") as handle:
            handle.write(data)
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def read_plurals():
    result = {}
    directory = RESOURCES / "Plurals"
    if not directory.exists():
        return result
    if directory.is_symlink() or not directory.is_dir():
        raise CatalogError(f"{directory}: expected a directory")
    for path in sorted(directory.iterdir()):
        if path.name.startswith("."):
            continue
        if path.suffix != ".json" or path.stem not in LOCALES:
            raise CatalogError(f"{path}: expected one of the 18 <locale>.json files")
        entries = read_json(path)
        if not isinstance(entries, dict):
            raise CatalogError(f"{path}: expected a key-to-plural object")
        result[path.stem] = entries
    return result


# Validation --------------------------------------------------------------------

def _catalog_strings(catalog, table):
    fields(catalog, CATALOG_FIELDS, table, CATALOG_FIELDS)
    if catalog[VERSION] != "1.0" or catalog[SOURCE_LANGUAGE] != "en" or not isinstance(catalog[STRINGS], dict):
        raise CatalogError(f"{table}: expected a version 1.0 catalog with English source")
    strings = catalog[STRINGS]
    if table == LOCALIZABLE and not strings:
        raise CatalogError("Localizable: the UI catalog is empty; run full extraction first")
    return strings


def _external_plural_keys(plurals, strings):
    plural_keys = set()
    for locale, entries in plurals.items():
        unknown = set(entries) - set(strings)
        if unknown:
            raise CatalogError(f"Plurals/{locale}.json: unknown catalog keys {sorted(unknown)[:5]}")
        plural_keys.update(entries)
    return plural_keys


def _validate_entry(key, entry, table):
    """Check one entry's metadata; return whether it has catalog plural variations."""
    place = f"{table}/{key}"
    text(key, f"{table} key")
    fields(entry, ENTRY_FIELDS, place)
    if COMMENT in entry:
        text(entry[COMMENT], f"{place} comment")
    for flag in (SHOULD_TRANSLATE, COMMENT_AUTO_GENERATED):
        if flag in entry and not isinstance(entry[flag], bool):
            raise CatalogError(f"{place}: {flag} must be Boolean")
    if entry.get(EXTRACTION_STATE) == STALE:
        raise CatalogError(f"{place}: stale entry; run full extraction or mark an intentional manual entry")
    if entry.get(EXTRACTION_STATE) not in (None, MANUAL, "extracted"):
        raise CatalogError(f"{place}: unsupported extractionState")
    localizations = entry.get(LOCALIZATIONS, {})
    if not isinstance(localizations, dict) or set(localizations) - set(LOCALES):
        raise CatalogError(f"{place}: unexpected localization code or structure")
    return any(isinstance(value, dict) and "variations" in value for value in localizations.values())


def _entry_source(key, localizations, table):
    english = localizations.get("en", {})
    if table == INFO_PLIST or STRING_UNIT in english:
        if set(english) != {STRING_UNIT}:
            raise CatalogError(f"{table}/{key}: an explicit English stringUnit is required")
        # A semantic key can have a different English defaultValue. Its
        # argument contract belongs to that value, not the lookup key.
        return string_unit(english[STRING_UNIT], f"{table}/{key}/en")
    return key


def _add_external_plurals(compiled, key, source, plurals, table):
    for locale, entries in plurals.items():
        if key not in entries:
            continue
        if locale in compiled and compiled[locale][1] is not None:
            raise CatalogError(f"{table}/{key}/{locale}: catalog and external plural variations overlap")
        plural, complete = external_plural(source, entries[key], locale, f"Plurals/{locale}/{key}")
        compiled[locale] = (None, plural, complete)


def _compile_entry(key, entry, table, plurals, is_plural):
    """Return {locale: (flat, plural, complete)} for every locale present, English always."""
    localizations = entry.get(LOCALIZATIONS, {})
    source = _entry_source(key, localizations, table)
    source_arguments = parse_format(source).arguments
    if source_arguments and set(source_arguments) != set(range(1, max(source_arguments) + 1)):
        raise CatalogError(f"{table}/{key}: source arguments have positional gaps")
    compiled = {}
    for locale, localization in localizations.items():
        compiled[locale] = catalog_localization(source, localization, locale, f"{table}/{key}/{locale}")
    _add_external_plurals(compiled, key, source, plurals, table)
    if "en" not in compiled:
        compiled["en"] = (source, None, True)
    if not compiled["en"][2] or is_plural and compiled["en"][1] is None:
        raise CatalogError(f"{table}/{key}/en: source plural forms are incomplete")
    return compiled


def _render_entry(key, entry, compiled, is_plural, rendered, missing):
    for locale in LOCALES:
        value = compiled.get(locale)
        if entry.get(SHOULD_TRANSLATE) is False:
            value = compiled["en"]
        complete = value is not None and value[2] and (not is_plural or value[1] is not None)
        if not complete:
            missing[locale].append(key)
            # InfoPlist falls back within already selected UI languages. This
            # never advertises a locale solely because its app name exists.
            value = compiled["en"]
        flat, plural, _ = value
        if flat is not None:
            rendered[locale][STRINGS][key] = flat
        if plural is not None:
            rendered[locale][PLURALS][key] = plural


def validate_catalog(catalog, table, plurals=None):
    """Return rendered locale tables and missing/incomplete keys, without writes."""
    strings = _catalog_strings(catalog, table)
    plurals = plurals or {}
    plural_keys = _external_plural_keys(plurals, strings)
    for key, entry in strings.items():
        if _validate_entry(key, entry, table):
            plural_keys.add(key)
    rendered = {locale: {STRINGS: {}, PLURALS: {}} for locale in LOCALES}
    missing = {locale: [] for locale in LOCALES}
    for key, entry in strings.items():
        is_plural = key in plural_keys
        compiled = _compile_entry(key, entry, table, plurals, is_plural)
        _render_entry(key, entry, compiled, is_plural, rendered, missing)
    return rendered, missing


def resources():
    plurals = read_plurals()
    output = {}
    for table in TABLES:
        catalog = read_json(RESOURCES / (table + ".xcstrings"))
        output[table] = validate_catalog(catalog, table, plurals if table == LOCALIZABLE else None)
    return output


def complete_locales(checked):
    """UI locales with no missing Localizable key; InfoPlist uses the same set."""
    return [locale for locale in LOCALES if not checked[LOCALIZABLE][1][locale]]


def report_missing(checked):
    count = 0
    for table, (_, missing) in checked.items():
        for locale, keys in missing.items():
            if keys:
                count += len(keys)
                sample = ", ".join(repr(key) for key in keys[:3])
                print(f"{table}/{locale}: {len(keys)} missing/incomplete; {sample}", file=sys.stderr)
    return count


def check(source_only):
    checked = resources()
    if not source_only and report_missing(checked):
        raise CatalogError("all 18 locales must be complete for the strict shipping check")
    locales = complete_locales(checked)
    print("Source and present-translation formats are valid. UI-complete locales: " + " ".join(locales))
    if not source_only:
        print("All 18 locales are complete in both catalogs and required plural forms.")


# Extraction merge --------------------------------------------------------------

def _owned_sources():
    return {path.resolve() for target in OWNED_TARGETS for path in (ROOT / "Sources" / target).rglob("*.swift")}


def _stringsdata_source(path):
    """Read one compiler .stringsdata file; return (data, resolved Swift source)."""
    data = read_json(path)
    fields(data, STRINGSDATA_FIELDS, str(path), STRINGSDATA_FIELDS)
    if data[VERSION] != 1 or not isinstance(data[TABLES_KEY], dict):
        raise CatalogError(f"{path}: unsupported compiler extraction format")
    source = Path(text(data[SOURCE], str(path)))
    source = (ROOT / source).resolve() if not source.is_absolute() else source.resolve()
    return data, source


def _add_extracted(found, entry, path):
    fields(entry, {"key", VALUE, COMMENT, "location"}, str(path), {"key"})
    key = text(entry["key"], str(path))
    value = text(entry.get(VALUE, key), str(path))
    comment = text(entry.get(COMMENT, ""), str(path))
    if not key:
        return
    existing = found.setdefault(key, {VALUE: value, COMMENTS: set()})
    if existing[VALUE] != value:
        raise CatalogError(f"{key}: conflicting English defaults in source")
    if comment:
        existing[COMMENTS].add(comment)


def _add_extracted_tables(found, tables, path):
    for table, entries in tables.items():
        if table != LOCALIZABLE or not isinstance(entries, list):
            raise CatalogError(f"{path}: unsupported extracted table {table!r}")
        for entry in entries:
            _add_extracted(found, entry, path)


def extracted_entries(directory):
    paths = sorted(directory.rglob("*.stringsdata"))
    if not paths:
        raise CatalogError("no .stringsdata found; run scripts/strings.sh extract (full scratch build)")
    found, seen_sources = {}, set()
    expected = _owned_sources()
    for path in paths:
        data, source = _stringsdata_source(path)
        if source not in expected:
            continue  # generated SwiftPM/dependency code is not owned UI copy
        seen_sources.add(source)
        _add_extracted_tables(found, data[TABLES_KEY], path)
    missing_sources = expected - seen_sources
    if missing_sources:
        sample = ", ".join(str(path.relative_to(ROOT)) for path in sorted(missing_sources)[:5])
        raise CatalogError(f"incomplete extraction: {len(missing_sources)} source files missing ({sample}); no catalog changed")
    if not found:
        raise CatalogError("extraction contains no owned UI keys; refusing to empty the catalog")
    return found


def _read_source_catalog(path):
    catalog = read_json(path) if path.exists() else {SOURCE_LANGUAGE: "en", STRINGS: {}, VERSION: "1.0"}
    fields(catalog, CATALOG_FIELDS, LOCALIZABLE, CATALOG_FIELDS)
    if not isinstance(catalog[STRINGS], dict):
        raise CatalogError("Localizable: strings must be an object")
    return catalog


def _dropped_keys(previous, found, allow_drop):
    for key, entry in previous.items():
        if not isinstance(entry, dict):
            raise CatalogError(f"Localizable/{key}: expected an entry object")
    dropped = [key for key, entry in previous.items()
               if key not in found and entry.get(EXTRACTION_STATE) != MANUAL and entry.get(SHOULD_TRANSLATE) is not False]
    if previous and len(dropped) * 100 > len(previous) * 5 and not allow_drop:
        raise CatalogError(f"{len(dropped)} of {len(previous)} keys would be dropped (>5%); inspect the full extraction, then use --allow-drop only if intended")
    return dropped


def _merge_extracted(strings, key, extracted):
    """Add or refresh one extracted key; return whether it was added."""
    comments, value = extracted[COMMENTS], extracted[VALUE]
    added = key not in strings
    if added:
        strings[key] = {LOCALIZATIONS: {"en": {STRING_UNIT: {"state": TRANSLATED, VALUE: value}}}}
    elif STRING_UNIT in strings[key].get(LOCALIZATIONS, {}).get("en", {}):
        english = strings[key][LOCALIZATIONS]["en"][STRING_UNIT]
        if english.get(VALUE) != value:
            raise CatalogError(f"{key}: English default changed; update its catalog value and review translations before extraction")
    entry = strings[key]
    if entry.get(EXTRACTION_STATE) == STALE:
        entry.pop(EXTRACTION_STATE)
    if comments and not entry.get(COMMENT):
        entry[COMMENT] = "\n".join(sorted(comments))
    # Existing locales, states, plural variations and manual metadata survive
    # unchanged. The compiler's key set is not a replacement translation table.
    return added


def merge(directory, allow_drop):
    found = extracted_entries(directory)
    path = RESOURCES / "Localizable.xcstrings"
    catalog = _read_source_catalog(path)
    result = copy.deepcopy(catalog)
    previous, strings = catalog[STRINGS], result[STRINGS]
    dropped = _dropped_keys(previous, found, allow_drop)
    for key in dropped:
        del strings[key]
    added = sum(_merge_extracted(strings, key, extracted) for key, extracted in found.items())
    result[STRINGS] = dict(sorted(strings.items()))
    validate_catalog(result, LOCALIZABLE, read_plurals())
    atomic_write(path, (json.dumps(result, ensure_ascii=False, indent=2) + "\n").encode("utf-8"))
    print(f"Localizable: {len(strings)} keys, {added} added, {len(dropped)} removed; existing translations and variations preserved")


# Bundle compilation ------------------------------------------------------------

def _output_directory(output):
    output = output.absolute()
    if output == RESOURCES.absolute() or output == ROOT:
        raise CatalogError("compile into the app bundle's resource directory, not source Resources")
    if output.is_symlink() or output.exists() and not output.is_dir():
        raise CatalogError(f"{output}: expected a resource directory, not a symbolic link")
    return output


def _is_obsolete(folder, locales):
    """Check a prior build's locale folder; return whether it is for a dropped locale."""
    if folder.is_symlink() or not folder.is_dir():
        raise CatalogError(f"{folder}: expected a regular localization directory")
    for child in folder.iterdir():
        if child.name in OUTPUTS and (child.is_symlink() or not child.is_file()):
            raise CatalogError(f"{child}: refusing to replace a nonregular resource")
    if folder.stem in locales:
        return False
    if any(child.name not in OUTPUTS for child in folder.iterdir()):
        raise CatalogError(f"{folder}: unsupported locale contains other resources; rebuild the bundle in a clean destination")
    return True


def _obsolete_folders(output, locales):
    if not output.exists():
        return []
    return [folder for folder in output.glob("*.lproj") if _is_obsolete(folder, locales)]


def _pending_tables(checked, locales, output):
    pending = {}
    for locale in locales:
        folder = output / (locale + ".lproj")
        for table in TABLES:
            rendered = checked[table][0][locale]
            pending[folder / (table + ".strings")] = plistlib.dumps(rendered[STRINGS], fmt=plistlib.FMT_BINARY, sort_keys=True)
            if rendered[PLURALS]:
                pending[folder / (table + ".stringsdict")] = plistlib.dumps(rendered[PLURALS], fmt=plistlib.FMT_XML, sort_keys=True)
    return pending


def _remove_stale(output, locales, pending, obsolete):
    """Remove stale owned plural files and unsupported locales from a prior build.

    No unrelated resources or folders are recursively deleted.
    """
    for locale in locales:
        for table in TABLES:
            old_plural = output / (locale + ".lproj") / (table + ".stringsdict")
            if old_plural not in pending and old_plural.exists():
                old_plural.unlink()
    for folder in obsolete:
        for child in folder.iterdir():
            child.unlink()
        folder.rmdir()


def compile_catalogs(output):
    checked = resources()  # validate every present locale before any bundle write
    locales = complete_locales(checked)
    output = _output_directory(output)
    obsolete = _obsolete_folders(output, locales)
    pending = _pending_tables(checked, locales, output)
    for path, data in pending.items():
        atomic_write(path, data)
    _remove_stale(output, locales, pending, obsolete)
    print("Compiled UI locales (InfoPlist uses the same set): " + " ".join(locales))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="command", required=True)
    merge_parser = commands.add_parser("merge")
    merge_parser.add_argument("stringsdata", type=Path)
    merge_parser.add_argument("--allow-drop", action="store_true")
    check_parser = commands.add_parser("check")
    check_parser.add_argument("--source", action="store_true")
    compile_parser = commands.add_parser("compile")
    compile_parser.add_argument("output_resource_dir", type=Path)
    args = parser.parse_args()
    try:
        if args.command == "merge":
            merge(args.stringsdata, args.allow_drop)
        elif args.command == "check":
            check(args.source)
        else:
            compile_catalogs(args.output_resource_dir)
    except (OSError, ValueError, TypeError) as error:  # CatalogError is a ValueError
        print(f"catalogs: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
